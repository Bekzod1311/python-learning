# Python comparison operations, also known as relational operators, 
# are used to compare two values and return a boolean result of either True or False. 
# These operators are essential for controlling program flow in conditional statements (if, elif, else) and loops. 

# Tere are the standard comparison operators in Python:
# Operator 	   Name	                  Description	                                                      Example
#   ==	     Equal to	              Checks if two operands have the same value.	                      5 == 5
#   !=	   Not equal to	              Checks if two operands have different values.	                      5 != 3
#   >	   Greater than	              Checks if the left operand is larger than the right.	              5 > 3
#   <	    Less than	              Checks if the left operand is smaller than the right.	              3 < 5
#   >=	Greater than or equal to	  Checks if the left operand is greater than or equal to the right.	  5 >= 5
#   <=	 Less than or equal to	      Checks if the left operand is less than or equal to the right.	  3 <= 5


