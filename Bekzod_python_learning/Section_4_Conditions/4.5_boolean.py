# Python's bool type represents truth values and has two possible built-in values: True and False. These are essential for decision-making in programming. 
# Key Concepts
# Values: The only two Boolean values are True and False. Note that they are capitalized and are keywords in Python, unlike strings "True" or "False".
# Data Type: The Boolean type is a subclass of the integer type (int). In numeric contexts, True behaves like the number 1 and False behaves like the number 0.
# Usage: Booleans are primarily used in conditional statements (if, elif, else) and loops (while) to control the flow of a program based on whether a condition is met. 


