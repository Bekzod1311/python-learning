# Computer
# A computer is an electronic machine that accepts input, processes data, stores information, 
# and produces output. It helps humans solve problems faster and more accurately.

# Main Parts of a Computer
# Hardware – physical parts you can touch (CPU, keyboard, mouse, monitor).
# Software – programs and instructions that tell the computer what to do (Windows, apps, games).

# Input Devices
# Input devices send data to the computer.
# Examples: keyboard, mouse, microphone, scanner, webcam.

# Output Devices
# Output devices show results from the computer.
# Examples: monitor, printer, speakers, projector.

# Input–Process–Output Relationship
# Input – you give data (typing, clicking).
# Process – the CPU works on the data.
# Output – the computer gives results (text, sound, images).

# Coding (Programming)

# Coding is writing instructions in a special language so a computer knows what to do and how to do it.
# Without coding, a computer is just hardware and cannot perform useful tasks.